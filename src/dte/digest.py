"""Build the weekly digest (Markdown), the map site (docs/), and optionally post to a webhook."""
from __future__ import annotations

import json
import os
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path

import requests

from . import db
from .config import ROOT, load_config
from .geocode import in_dc_area
from .models import TZ

DIGEST_DIR = ROOT / "digest"
DOCS_DIR = ROOT / "docs"
TEMPLATE = Path(__file__).with_name("map_template.html")


def approved_events(con, start: datetime, days: int) -> list[dict]:
    end = start + timedelta(days=days)
    rows = con.execute(
        "SELECT * FROM events WHERE approved='y' AND start_dt >= ? AND start_dt < ? ORDER BY start_dt",
        (start.isoformat(), end.isoformat()),
    ).fetchall()
    return [db.row_to_dict(r) for r in rows]


def _fmt_time(ev: dict) -> str:
    s = datetime.fromisoformat(ev["start_dt"])
    if s.hour == 0 and s.minute == 0:
        return "time TBD"
    t = s.strftime("%-I:%M %p") if os.name != "nt" else s.strftime("%I:%M %p").lstrip("0")
    if ev.get("end_dt"):
        e = datetime.fromisoformat(ev["end_dt"])
        t += "–" + (e.strftime("%-I:%M %p") if os.name != "nt" else e.strftime("%I:%M %p").lstrip("0"))
    return t


def _where(ev: dict) -> str:
    if ev.get("virtual") and not ev.get("location"):
        return "Virtual"
    loc = ev.get("location") or "location TBD"
    return f"{loc} (+ virtual)" if ev.get("virtual") else loc


def flagged_sources(con, threshold: int) -> list[tuple[str, int, str]]:
    out = []
    for s in db.latest_status(con):
        n = db.consecutive_failures(con, s["source_name"])
        if n >= threshold:
            out.append((s["source_name"], n, s.get("message") or ""))
    return out


def render_markdown(events: list[dict], start: datetime, days: int, flagged: list[tuple[str, int, str]]) -> str:
    iso_year, iso_week, _ = start.isocalendar()
    lines = [
        f"# DC emerging-tech policy events — week {iso_year}-W{iso_week:02d}",
        "",
        f"Covering {start.date().isoformat()} to {(start + timedelta(days=days - 1)).date().isoformat()}. "
        f"{len(events)} approved events. Map: see `docs/index.html` (GitHub Pages).",
        "",
    ]
    by_day: dict[str, list[dict]] = defaultdict(list)
    for e in events:
        by_day[e["start_dt"][:10]].append(e)
    for day in sorted(by_day):
        d = datetime.fromisoformat(day)
        lines.append(f"## {d.strftime('%A, %B ')}{d.day}")
        lines.append("")
        for e in by_day[day]:
            chips = " ".join(f"`{t}`" for t in (e.get("topics") or []))
            lines.append(f"### [{e['title']}]({e['url']})")
            lines.append(f"{chips}  ")
            lines.append(f"**{e.get('host_org') or e.get('source_name')}** · {_fmt_time(e)} · {_where(e)}  ")
            if e.get("one_line_why"):
                lines.append(f"_{e['one_line_why']}_  ")
            if e.get("review_note") and not e["review_note"].startswith("auto-approved"):
                lines.append(f"Reviewer note: {e['review_note']}  ")
            lines.append("")
    if not events:
        lines.append("_No approved events in this window. Run `uv run dte review` and approve some._")
        lines.append("")
    lines.append("---")
    if flagged:
        lines.append("**⚠ Sources needing attention** (failed on consecutive runs — check the URL in sources.yaml):")
        for name, n, msg in flagged:
            lines.append(f"- {name}: {n} failures in a row. Last error: {msg[:120]}")
    else:
        lines.append("All sources healthy.")
    lines.append("")
    lines.append("_Generated by dc-tech-events. Events are pulled automatically and approved by a human reviewer._")
    return "\n".join(lines) + "\n"


def build_site(events: list[dict], start: datetime, days: int, flagged: list[tuple[str, int, str]], cfg: dict) -> None:
    DOCS_DIR.mkdir(exist_ok=True)
    payload = {
        "generated_at": datetime.now(TZ).replace(microsecond=0).isoformat(),
        "window_start": start.date().isoformat(),
        "window_days": days,
        "map_center": cfg["map_center"],
        "map_zoom": cfg["map_zoom"],
        "flagged_sources": [{"name": n, "failures": k} for n, k, _ in flagged],
        "events": [
            {
                "id": e["id"], "title": e["title"], "start": e["start_dt"], "end": e.get("end_dt"),
                "host": e.get("host_org") or e.get("source_name"), "source": e.get("source_name"),
                "location": e.get("location"), "virtual": bool(e.get("virtual")), "url": e["url"],
                "topics": e.get("topics") or [], "fit": e.get("fit_score"), "why": e.get("one_line_why"),
                "description": e.get("description_short"), "speakers": e.get("speakers") or [],
                "lat": e.get("lat"), "lon": e.get("lon"), "in_dc": in_dc_area(e.get("lat"), e.get("lon")),
                "time": _fmt_time(e), "where": _where(e),
            }
            for e in events
        ],
    }
    (DOCS_DIR / "events.json").write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    html = TEMPLATE.read_text(encoding="utf-8").replace("/*__EVENTS_JSON__*/null", json.dumps(payload, ensure_ascii=False))
    (DOCS_DIR / "index.html").write_text(html, encoding="utf-8")
    (DOCS_DIR / ".nojekyll").write_text("", encoding="utf-8")


def post_webhook(md: str, url: str) -> bool:
    text = md if len(md) < 3500 else md[:3400] + "\n…(truncated; full digest in the repo)"
    body = {"text": text, "content": text}  # Slack reads `text`, Discord reads `content`
    try:
        r = requests.post(url, json=body, timeout=20)
        return r.status_code < 300
    except requests.RequestException:
        return False


def run_digest(today: datetime | None = None) -> Path:
    cfg = load_config()
    today = today or datetime.now(TZ)
    start = today.replace(hour=0, minute=0, second=0, microsecond=0)
    days = int(cfg["digest_days_ahead"])
    con = db.connect()
    events = approved_events(con, start, days)
    flagged = flagged_sources(con, int(cfg["failure_flag_threshold"]))
    md = render_markdown(events, start, days, flagged)
    DIGEST_DIR.mkdir(exist_ok=True)
    y, w, _ = start.isocalendar()
    path = DIGEST_DIR / f"{y}-W{w:02d}.md"
    path.write_text(md, encoding="utf-8")
    build_site(events, start, days, flagged, cfg)
    con.close()
    hook = os.environ.get("DIGEST_WEBHOOK_URL")
    if hook:
        ok = post_webhook(md, hook)
        print("webhook:", "sent" if ok else "FAILED")
    return path
